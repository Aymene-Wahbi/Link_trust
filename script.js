let currentLang = 'en';

// DOM elements
const themeToggle = document.getElementById('themeToggle');
const langSelect = document.getElementById('langSelect');
const urlForm = document.getElementById('urlForm');
const urlInput = document.getElementById('urlInput');
const clearBtn = document.getElementById('clearBtn');
const analyzeBtn = document.getElementById('analyzeBtn');
const loadingState = document.getElementById('loadingState');
const resultsContainer = document.getElementById('resultsContainer');

// Theme Switch
themeToggle.addEventListener('click', () => {
    document.documentElement.classList.toggle('dark');
});

// Language Switch (EN Primary)
langSelect.addEventListener('change', (e) => {
    currentLang = e.target.value;

    // Manage RTL for Arabic
    if (currentLang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
    }

    updateTranslations();
});

function updateTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[currentLang][key]) el.innerText = i18n[currentLang][key];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (i18n[currentLang][key]) el.placeholder = i18n[currentLang][key];
    });
}

urlInput.addEventListener('input', () => {
    clearBtn.classList.toggle('hidden', !urlInput.value);
});

clearBtn.addEventListener('click', () => {
    urlInput.value = '';
    clearBtn.classList.add('hidden');
    urlInput.focus();
});

function loadExample(url) {
    urlInput.value = url;
    clearBtn.classList.remove('hidden');
    analyzeUrl(url);
}

urlForm.addEventListener('submit', (e) => {
    e.preventDefault();
    const url = urlInput.value.trim();
    if (url) analyzeUrl(url);
});

function analyzeUrl(rawUrl) {
    resultsContainer.classList.add('hidden');
    loadingState.classList.remove('hidden');
    analyzeBtn.disabled = true;

    setTimeout(() => {
        loadingState.classList.add('hidden');
        analyzeBtn.disabled = false;

        const report = performAnalysis(rawUrl);
        renderResults(report);

        resultsContainer.classList.remove('hidden');
        resultsContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }, 1000);
}

function performAnalysis(rawUrl) {
    let processedUrl = rawUrl;
    if (!/^https?:\/\//i.test(processedUrl)) processedUrl = 'http://' + processedUrl;

    let parsed;
    try { parsed = new URL(processedUrl); } catch (e) { parsed = { hostname: rawUrl, protocol: 'HTTP:' }; }

    const hostname = parsed.hostname.toLowerCase();
    const protocol = parsed.protocol.replace(':', '').toUpperCase();

    let score = 100;
    const criteria = [];

    // Protocol Check
    const isHttps = protocol === 'HTTPS';
    if (!isHttps) score -= 30;
    criteria.push({
        title: currentLang === 'ar' ? "تشفير SSL" : (currentLang === 'fr' ? "Chiffrement SSL" : "SSL Encryption"),
        status: isHttps ? 'success' : 'danger',
        icon: isHttps ? 'fa-lock' : 'fa-unlock',
        desc: isHttps ? (currentLang === 'fr' ? 'Protocole HTTPS actif.' : 'HTTPS active.') : (currentLang === 'fr' ? 'Connexion HTTP non sécurisée.' : 'Insecure HTTP connection.')
    });

    // Typosquatting Check
    const brands = ['paypal', 'google', 'facebook', 'amazon', 'apple', 'microsoft', 'netflix', 'bankofamerica'];
    let typosquat = brands.some(b => hostname.includes(b.replace('a','1')) || (hostname.includes(b) && !hostname.endsWith(b + '.com')));
    if (typosquat) {
        score -= 45;
        criteria.push({
            title: currentLang === 'ar' ? "انتحال شخصية" : (currentLang === 'fr' ? "Usurpation (Typosquatting)" : "Typosquatting"),
            status: 'danger',
            icon: 'fa-mask',
            desc: currentLang === 'fr' ? "Tentative d'imitation d'une marque connue." : "Imitating a well-known brand."
        });
    } else {
        criteria.push({
            title: currentLang === 'ar' ? "تحليل النطاق" : (currentLang === 'fr' ? "Analyse du Domaine" : "Domain Analysis"),
            status: 'success',
            icon: 'fa-font',
            desc: currentLang === 'fr' ? "Pas d'usurpation évidente trouvée." : "No obvious brand imitation found."
        });
    }

    // Shortener Check
    const isShortener = ['bit.ly', 'tinyurl.com', 'goo.gl'].some(s => hostname.includes(s));
    if (isShortener) {
        score -= 20;
        criteria.push({
            title: currentLang === 'ar' ? "إعادة توجيه" : (currentLang === 'fr' ? "Redirection" : "Redirection"),
            status: 'warning',
            icon: 'fa-compress',
            desc: currentLang === 'fr' ? "Raccourcisseur masque la destination réelle." : "Shortener hides the destination URL."
        });
    }

    score = Math.max(0, Math.min(100, score));

    return { domain: hostname, protocol, score, criteria };
}

function renderResults(report) {
    document.getElementById('analysisTimestamp').innerText = new Date().toLocaleTimeString();
    document.getElementById('parsedDomain').innerText = report.domain;
    document.getElementById('parsedProtocol').innerText = report.protocol;

    const scoreValEl = document.getElementById('scoreValue');
    const scoreCircle = document.getElementById('scoreCircle');
    const scoreLabel = document.getElementById('scoreLabel');
    const verdictTitle = document.getElementById('verdictTitle');
    const verdictDescription = document.getElementById('verdictDescription');

    scoreValEl.innerText = report.score;
    const circumference = 263.89;
    scoreCircle.style.strokeDashoffset = circumference - (report.score / 100) * circumference;

    const recBox = document.getElementById('recommendationBox');
    const recIcon = document.getElementById('recIcon');
    const recTitle = document.getElementById('recTitle');
    const recText = document.getElementById('recText');

    if (report.score >= 80) {
        scoreCircle.style.stroke = "#10b981";
        scoreLabel.className = "mt-4 px-4 py-1.5 rounded-full text-xs font-bold uppercase tracking-wider bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border border-emerald-500/20";
        scoreLabel.innerText = "Safe";

        verdictTitle.innerText = i18n[currentLang].safeTitle;
        verdictDescription.innerText = i18n[currentLang].safeDesc;

        recBox.className = "p-6 rounded-2xl bg-emerald-500/10 border border-emerald-500/20 text-emerald-800 dark:text-emerald-300 flex items-start gap-4";
        recIcon.className = "p-3 rounded-xl bg-emerald-500/20 text-emerald-600 dark:text-emerald-400 text-xl flex-shrink-0";
        recIcon.innerHTML = `<i class="fa-solid fa-circle-check"></i>`;
        recTitle.innerText = i18n[currentLang].safeTitle;
        recText.innerText = i18n[currentLang].recSafe;
    } else if (report.score >= 50) {
        scoreCircle.style.stroke = "#f59e0b";
        scoreLabel.className = "mt-4 px-4 py-1.5 rounded-full text-xs font-bold uppercase tracking-wider bg-amber-500/10 text-amber-600 dark:text-amber-400 border border-amber-500/20";
        scoreLabel.innerText = "Warning";

        verdictTitle.innerText = i18n[currentLang].warnTitle;
        verdictDescription.innerText = i18n[currentLang].warnDesc;

        recBox.className = "p-6 rounded-2xl bg-amber-500/10 border border-amber-500/20 text-amber-800 dark:text-amber-300 flex items-start gap-4";
        recIcon.className = "p-3 rounded-xl bg-amber-500/20 text-amber-600 dark:text-amber-400 text-xl flex-shrink-0";
        recIcon.innerHTML = `<i class="fa-solid fa-triangle-exclamation"></i>`;
        recTitle.innerText = i18n[currentLang].warnTitle;
        recText.innerText = i18n[currentLang].recWarn;
    } else {
        scoreCircle.style.stroke = "#f43f5e";
        scoreLabel.className = "mt-4 px-4 py-1.5 rounded-full text-xs font-bold uppercase tracking-wider bg-rose-500/10 text-rose-600 dark:text-rose-400 border border-rose-500/20";
        scoreLabel.innerText = "Phishing Risk";

        verdictTitle.innerText = i18n[currentLang].dangerTitle;
        verdictDescription.innerText = i18n[currentLang].dangerDesc;

        recBox.className = "p-6 rounded-2xl bg-rose-500/10 border border-rose-500/20 text-rose-800 dark:text-rose-300 flex items-start gap-4";
        recIcon.className = "p-3 rounded-xl bg-rose-500/20 text-rose-600 dark:text-rose-400 text-xl flex-shrink-0";
        recIcon.innerHTML = `<i class="fa-solid fa-skull-crossbones"></i>`;
        recTitle.innerText = i18n[currentLang].dangerTitle;
        recText.innerText = i18n[currentLang].recDanger;
    }

    const grid = document.getElementById('criteriaGrid');
    grid.innerHTML = '';
    report.criteria.forEach(item => {
        const card = document.createElement('div');
        card.className = "p-5 rounded-2xl glass-card flex flex-col justify-between space-y-2";
        card.innerHTML = `
            <div class="flex items-center gap-3">
                <div class="w-9 h-9 rounded-xl ${item.status === 'success' ? 'bg-emerald-500/10 text-emerald-600 dark:text-emerald-400' : 'bg-rose-500/10 text-rose-600 dark:text-rose-400'} flex items-center justify-center font-bold">
                    <i class="fa-solid ${item.icon}"></i>
                </div>
                <div>
                    <h4 class="font-bold text-sm heading-text">${item.title}</h4>
                    <p class="text-xs sub-text">${item.desc}</p>
                </div>
            </div>
        `;
        grid.appendChild(card);
    });
}